CREATE WAREHOUSE IF NOT EXISTS SUPPORT_WH
WITH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE SUPPORT_WH;

CREATE DATABASE IF NOT EXISTS SUPPORT_INTELLIGENCE;

CREATE SCHEMA IF NOT EXISTS SUPPORT_INTELLIGENCE.RAW;

CREATE SCHEMA IF NOT EXISTS SUPPORT_INTELLIGENCE.ANALYTICS;


CREATE TABLE IF NOT EXISTS
SUPPORT_INTELLIGENCE.RAW.SUPPORT_TICKETS (
    TICKET_ID NUMBER(10,0),
    CUSTOMER VARCHAR(255),
    PRODUCT VARCHAR(255),
    DESCRIPTION VARCHAR(2000),
    PRIORITY VARCHAR(20),
    STATUS VARCHAR(30),
    CREATED_AT DATE
);