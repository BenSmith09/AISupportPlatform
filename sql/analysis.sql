--Step 9 Outstanding support tickets
SELECT
    PRODUCT,
    PRIORITY,
    COUNT(*) AS OPEN_TICKETS
FROM SUPPORT_INTELLIGENCE.RAW.SUPPORT_TICKETS
WHERE STATUS IN ('Open', 'In Progress')
GROUP BY PRODUCT, PRIORITY
ORDER BY OPEN_TICKETS DESC;

--Analyse monthly ticket trends
SELECT
    DATE_TRUNC('MONTH', CREATED_AT) AS MONTH,
    COUNT(*) AS TOTAL_TICKETS
FROM SUPPORT_INTELLIGENCE.RAW.SUPPORT_TICKETS
GROUP BY MONTH
ORDER BY MONTH;

--Most common support issues
SELECT
    PRODUCT,
    DESCRIPTION,
    COUNT(*) AS OCCURRENCES
FROM SUPPORT_INTELLIGENCE.RAW.SUPPORT_TICKETS
GROUP BY PRODUCT, DESCRIPTION
ORDER BY OCCURRENCES DESC
LIMIT 10;

--Step 12: Create reporting view
CREATE OR REPLACE VIEW
SUPPORT_INTELLIGENCE.ANALYTICS.TICKET_SUMMARY AS

SELECT
    PRODUCT,
    PRIORITY,
    STATUS,
    COUNT(*) AS TICKET_COUNT
FROM SUPPORT_INTELLIGENCE.RAW.SUPPORT_TICKETS
GROUP BY
PRODUCT, PRIORITY, STATUS;